"""Centralized feasibility reason-code enum (Phase 6).

A single source of truth for every code FeasibilityService can emit —
routes, the Gemini tool, and the frontend all import from here rather
than re-declaring string literals. Only codes actually implemented by
FeasibilityService appear (docs/DECISIONS.md ADR-040 family).
"""

