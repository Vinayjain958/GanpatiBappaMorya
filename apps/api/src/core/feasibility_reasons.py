    BUDGET_EXCEEDED = "BUDGET_EXCEEDED"
    PRICE_UNAVAILABLE = "PRICE_UNAVAILABLE"
    UNSUPPORTED_CURRENCY = "UNSUPPORTED_CURRENCY"

    DURATION_EXCEEDED = "DURATION_EXCEEDED"
    DURATION_UNAVAILABLE = "DURATION_UNAVAILABLE"

    OUTSIDE_AVAILABLE_TIME = "OUTSIDE_AVAILABLE_TIME"

    OPENING_HOURS_CONFLICT = "OPENING_HOURS_CONFLICT"
    OPENING_HOURS_UNAVAILABLE = "OPENING_HOURS_UNAVAILABLE"

    TRAVEL_TIME_EXCEEDED = "TRAVEL_TIME_EXCEEDED"
    TRAVEL_TIME_UNAVAILABLE = "TRAVEL_TIME_UNAVAILABLE"
    MAX_DISTANCE_EXCEEDED = "MAX_DISTANCE_EXCEEDED"

    GROUP_SIZE_EXCEEDS_CAPACITY = "GROUP_SIZE_EXCEEDS_CAPACITY"
    CAPACITY_UNAVAILABLE = "CAPACITY_UNAVAILABLE"

    ACCESSIBILITY_NOT_SUPPORTED = "ACCESSIBILITY_NOT_SUPPORTED"
